# 2. Admin assigns a ticket to an engineer
@router.patch("/{ticket_id}/assign")
def assign_ticket(
    ticket_id: int,
    assignment: TicketAssign,
    db: Session = Depends(get_db),
    current_user: User = Depends(require_admin)
):
    ticket, error = ticket_service.assign_ticket(
        db=db,
        ticket_id=ticket_id,
        assignee_id=assignment.assignee_id,
        current_user_id=current_user.id
    )

    if error == "ticket_not_found":
        raise HTTPException(
            status_code=404,
            detail="Ticket not found"
        )

    if error == "user_not_found":
        raise HTTPException(
            status_code=404,
            detail="Engineer not found"
        )

    if error == "not_engineer":
        raise HTTPException(
            status_code=400,
            detail="Selected user is not an engineer"
        )

    if error == "already_assigned":
        raise HTTPException(
            status_code=400,
            detail="Ticket is already assigned to this engineer"
        )

    return {
        "message": "Ticket assigned successfully",
        "ticket_id": ticket.id,
        "assignee_id": ticket.assignee_id
    }

