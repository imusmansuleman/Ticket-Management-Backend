# 5. Engineer/Admin updates ticket status
@router.patch("/{ticket_id}/status")
def change_ticket_status(
    ticket_id: int,
    status_data: TicketStatusUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    ticket, error = ticket_service.update_ticket_status(
        db=db,
        ticket_id=ticket_id,
        new_status=status_data.status,
        current_user=current_user
    )

    if error == "ticket_not_found":
        raise HTTPException(
            status_code=404,
            detail="Ticket not found"
        )

    if error == "not_assigned":
        raise HTTPException(
            status_code=403,
            detail="This ticket is not assigned to you"
        )

    if error == "permission_denied":
        raise HTTPException(
            status_code=403,
            detail="You cannot update ticket status"
        )

    if error == "invalid_transition":
        raise HTTPException(
            status_code=400,
            detail="Invalid ticket status transition"
        )

    return {
        "message": "Ticket status updated successfully",
        "ticket_id": ticket.id,
        "status": ticket.status.value
    }

